"""Externally sourced chart-selection rules and separately specified user policies.

The policy oracle CSV was authored from official WHO/CDC/gigs references;
it is not generated by GrowthCharts' selector implementation.
"""

from __future__ import annotations

import csv
from pathlib import Path

import pytest
from pedgrowth import AgeDefinition, AgeType, AgeUnit, GrowthChartsCalculator
from pedgrowth.data.cdc import CdcClinicalPlan, CdcPlan, CdcWithWhoFallbackPlan, WhoWithCdcFallbackPlan
from pedgrowth.data.intergrowth import IntergrowthPlan
from pedgrowth.data.who2006 import WhoPlan
from pedgrowth.exceptions import DataNotFoundError

PATH = Path(__file__).parent / "fixtures/policy_review.csv"
with PATH.open(newline="", encoding="utf-8") as f:
    CASES = list(csv.DictReader(f))

PLANS = {
    "WhoPlan": WhoPlan,
    "CdcPlan": CdcPlan,
    "CdcWithWhoFallbackPlan": CdcWithWhoFallbackPlan,
    "WhoWithCdcFallbackPlan": WhoWithCdcFallbackPlan,
    "CdcClinicalPlan": CdcClinicalPlan,
    "IntergrowthPlan": IntergrowthPlan,
}


@pytest.mark.parametrize(
    "row",
    CASES,
    ids=lambda case: f"{case['plan']}-{case['indicator']}-{case['age']}-{case['sex']}-{case['coordinate']}",
)
def test_formally_specified_plan_reference_and_coordinate(row):
    plan = PLANS[row["plan"]]()
    kwargs = {
        "indicator": row["indicator"],
        "sex": row["sex"],
        "age": float(row["age"]),
        "age_definition": AgeDefinition(AgeType(row["age_type"]), AgeUnit(row["unit"])),
    }
    if row["coordinate"]:
        kwargs["coordinate"] = float(row["coordinate"])
    if row["expected_reference"] == "invalid_age":
        with pytest.raises(ValueError, match="postmenstrual"):
            plan.resolve(**kwargs)
        return
    if row["expected_reference"] == "none":
        with pytest.raises(DataNotFoundError):
            plan.resolve(**kwargs)
        return
    reference = plan.resolve(**kwargs)
    assert reference.reference_id == row["expected_reference"]
    assert reference.coordinate == pytest.approx(float(row["selected_coordinate"]), abs=1e-8)
    assert reference.measurement_offset == pytest.approx(float(row["measurement_offset"]), abs=1e-10)
    calc = GrowthChartsCalculator(plan=plan)
    from_calc = calc.resolve(**kwargs)
    assert from_calc == reference
    numpy, ids = calc.calculate_numpy(
        indicator=row["indicator"],
        measurements=[30.0],
        sexes=[row["sex"]],
        ages=[float(row["age"])],
        age_definition=kwargs["age_definition"],
        coordinates=[float(row["coordinate"])] if row["coordinate"] else None,
        errors="coerce",
    )
    assert ids[0] == row["expected_reference"]
    assert numpy.shape == (1,)


def test_independent_policy_oracle_covers_every_named_plan():
    assert set(row["plan"] for row in CASES) == set(PLANS)
    assert {row["source"] for row in CASES} == {
        "WHO_2006",
        "WHO_2007",
        "WHO_ANTHRO_POSITION",
        "CDC_SOURCE",
        "USER_PRECEDENCE",
        "CDC_POLICY",
        "CDC_POLICY_LIMITED",
        "GIGS_STANDARD",
    }
    assert len(CASES) >= 60
